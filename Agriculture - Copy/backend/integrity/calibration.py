"""Source-conditioned calibration with hierarchical backoff.

Standard conditional (Mondrian) conformal prediction partitions calibration
residuals by a taxonomy over the *response and its covariates*. This module
partitions by the **provenance state of the input acquisition pipeline** --
whether a value was retrieved live, served from a short-lived cache, supplied
by a forecast, substituted from long-run climatology, or generated by a proxy
model. The distinction that matters is that the value is usually *present and
plausible* in every one of those cases; only the production state differs.

Statistical honesty, stated up front because it constrains how the result may
be described:

* A split-conformal quantile ``Q(alpha) = Quantile(ceil((n+1)(1-alpha))/n)`` of
  ``n`` absolute residuals carries the finite-sample coverage guarantee only
  when the calibration points are exchangeable with the test point *within the
  selected partition* and ``n >= ceil(1/alpha) - 1``. Below the floor the
  quantile is simply an order statistic and carries no guarantee.

* When a partition falls back to a pooled residual set, multiplying that
  quantile by an inflation factor **does not restore the guarantee**. Widening
  is a monotone heuristic. This module reports ``guarantee_level`` on every
  call so callers cannot present a backed-off interval as a calibrated one.

The inflation factor is therefore not claimed as a correction. It is a
prior-set shrinking target, and its only justification is the measured
empirical coverage reported in the validation harness.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Dict, List, Optional, Sequence, Tuple

import numpy as np

DEFAULT_ALPHA = 0.10
#: Minimum partition size for the finite-sample guarantee to be meaningful at
#: alpha = 0.10 (the theoretical floor is ceil(1/alpha) - 1 = 9; 20 is used
#: because the partitions are populated by correlated re-runs of a small number
#: of real seasons, so effective sample size is below the nominal count).
DEFAULT_MIN_PARTITION = 20
DEFAULT_INFLATION = 1.35


def conformal_quantile(residuals: Sequence[float], alpha: float = DEFAULT_ALPHA) -> float:
    """Split-conformal absolute-residual quantile with the finite-sample correction."""

    arr = np.asarray(sorted(float(r) for r in residuals), dtype=float)
    n = arr.size
    if n == 0:
        return 0.0
    q_level = min(np.ceil((n + 1) * (1.0 - alpha)) / n, 1.0)
    return float(np.quantile(arr, q_level, method="higher"))


@dataclass(frozen=True)
class QualityKey:
    """The composite provenance key that selects a calibration partition.

    ``weather`` is the degradation category of the weather record,
    ``vegetation`` is the per-observation quality band, and ``conflict`` is the
    collapsed cross-source agreement state.
    """

    weather: str
    vegetation: str
    conflict: str

    def label(self) -> str:
        return f"W{self.weather}|V{self.vegetation}|C{self.conflict}"


@dataclass
class Selection:
    partition_label: str
    quantile: float
    n_residuals: int
    alpha: float
    inflation_applied: float
    backoff_depth: int
    guarantee_level: str
    path: List[Tuple[str, int]] = field(default_factory=list)

    @property
    def calibrated(self) -> bool:
        return self.guarantee_level == "finite_sample_conformal"

    def to_dict(self) -> Dict:
        return {
            "partition_label": self.partition_label,
            # Kept at full precision: the interval is computed from this value,
            # and rounding it here would make a faithful replay disagree with
            # the stored output.
            "quantile": self.quantile,
            "n_residuals": self.n_residuals,
            "alpha": self.alpha,
            "inflation_applied": self.inflation_applied,
            "backoff_depth": self.backoff_depth,
            "guarantee_level": self.guarantee_level,
            "is_calibrated": self.calibrated,
            "backoff_path": [f"{label}:{n}" for label, n in self.path],
        }


class CalibrationStore:
    """Absolute residuals of a fixed base model, indexed by provenance key."""

    def __init__(
        self,
        alpha: float = DEFAULT_ALPHA,
        min_partition: int = DEFAULT_MIN_PARTITION,
        inflation: float = DEFAULT_INFLATION,
    ) -> None:
        self.alpha = alpha
        self.min_partition = min_partition
        self.inflation = inflation
        self._partitions: Dict[str, List[float]] = {}
        self._n_observations = 0

    # -- population -------------------------------------------------------
    def add(self, key: QualityKey, residual: float) -> None:
        """Insert one residual into every stratum it belongs to.

        Strata are materialised on write rather than reconstructed by wildcard
        matching at read time. Each stratum therefore counts exactly the
        residuals that satisfy it, and a stratum and its own sub-strata never
        disagree about membership.
        """

        value = abs(float(residual))
        if not np.isfinite(value):
            return
        w, v, c = key.weather, key.vegetation, key.conflict
        labels = (
            f"W{w}|V{v}|C{c}",
            f"W{w}|V{v}|C*",
            f"W{w}|V*|C{c}",
            f"W{w}|V*|C*",
            f"W*|V{v}|C*",
        )
        for label in labels:
            self._partitions.setdefault(label, []).append(value)
        self._n_observations += 1

    def add_many(self, entries: Sequence[Tuple[QualityKey, float]]) -> None:
        for key, residual in entries:
            self.add(key, residual)

    @property
    def total(self) -> int:
        """Number of distinct residual observations, not the sum over strata."""

        return self._n_observations

    @property
    def exact_partition_labels(self) -> List[str]:
        return sorted(k for k in self._partitions if not k.endswith("*") and k.count("|") == 2 and "*" not in k.split("|")[1])

    def count(self, label: str) -> int:
        return len(self._partitions.get(label, []))

    # -- selection --------------------------------------------------------
    def _candidate_labels(self, key: QualityKey) -> List[Tuple[str, int]]:
        """Backoff ladder, most specific first.

        The ladder drops one conditioning axis at a time rather than
        collapsing straight to the pooled set, so a sparse composite cell can
        still borrow from a stratum that retains two of its three axes.
        """

        w, v, c = key.weather, key.vegetation, key.conflict
        return [
            (f"W{w}|V{v}|C{c}", 0),
            (f"W{w}|V{v}|C*", 1),
            (f"W{w}|V*|C{c}", 1),
            (f"W{w}|V*|C*", 2),
            (f"W*|V{v}|C*", 2),
            ("POOLED", 99),
        ]

    def _resolve(self, label: str) -> List[float]:
        if label == "POOLED":
            # Recomputed from exact partitions so that the pooled set holds
            # each observation exactly once, not once per stratum it touched.
            merged: List[float] = []
            for exact in self.exact_partition_labels:
                merged.extend(self._partitions[exact])
            return merged
        return self._partitions.get(label, [])

    def select(self, key: QualityKey) -> Selection:
        path: List[Tuple[str, int]] = []
        fallback_used = False
        chosen_label = "POOLED"
        chosen_n = 0
        chosen_depth = 99

        for label, depth in self._candidate_labels(key):
            values = self._resolve(label)
            n = len(values)
            path.append((label, n))
            if n >= self.min_partition:
                chosen_label, chosen_n, chosen_depth = label, n, depth
                break
            if label != "POOLED":
                fallback_used = True

        if chosen_label == "POOLED" and not self._partitions:
            return Selection(
                partition_label="EMPTY",
                quantile=0.0,
                n_residuals=0,
                alpha=self.alpha,
                inflation_applied=1.0,
                backoff_depth=99,
                guarantee_level="none",
                path=path,
            )

        values = self._resolve(chosen_label)
        base_q = conformal_quantile(values, self.alpha)
        inflation = self.inflation if fallback_used else 1.0
        quantile = base_q * inflation

        if chosen_label == "POOLED" or fallback_used:
            guarantee = "heuristic_inflated_pooled"
        else:
            guarantee = "finite_sample_conformal"

        return Selection(
            partition_label=chosen_label,
            quantile=float(quantile),
            n_residuals=int(chosen_n),
            alpha=self.alpha,
            inflation_applied=float(inflation),
            backoff_depth=int(chosen_depth),
            guarantee_level=guarantee,
            path=path,
        )


class PooledBaselineStore:
    """The comparison baseline: one pooled residual set, one constant interval.

    This reproduces the behaviour of the existing production system, where a
    single hard-coded margin (``yield_model.py:18``) is applied to every
    prediction regardless of input provenance.
    """

    def __init__(self, alpha: float = DEFAULT_ALPHA) -> None:
        self.alpha = alpha
        self._residuals: List[float] = []

    def add(self, residual: float) -> None:
        value = abs(float(residual))
        if np.isfinite(value):
            self._residuals.append(value)

    @property
    def total(self) -> int:
        return len(self._residuals)

    def quantile(self) -> float:
        return conformal_quantile(self._residuals, self.alpha)
